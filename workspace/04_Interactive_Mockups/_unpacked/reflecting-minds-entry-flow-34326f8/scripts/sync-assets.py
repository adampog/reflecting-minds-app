#!/usr/bin/env python3
"""Copy pinned Art Department items from yt-art-library into app/assets/, byte-identical.

Each pin is a library item folder plus the sha256 of its MANIFEST.sha256. The script refuses
to copy if the manifest hash differs or any listed file fails its check. It also writes
app/assets/sprite.js (browsers block external SVG <use> on file:// pages) and app/assets/plates.js (plate paths and alt text).
Usage: python3 scripts/sync-assets.py
"""
import hashlib, json, pathlib, shutil, sys

LIB = pathlib.Path('/home/alan/Documents/Codex/2026-10-15/task-4/shared-art-assets/yt-art-library')
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'app' / 'assets'
PINS = [  # (library path, MANIFEST.sha256 sha256)
    ('rma/tokens/entry-room/v0.1.0', '6a36cf954e3402c5790aabc9f3242bd233be20ba912c907cde8a7485468aea8c'),
    ('rma/icons/entry-set/v0.1.2', '706fbd93739ed4445de0870ca3aeb115da01be34b08a45d54e8dbb7423f2668a'),
    ('rma/plates/door-deck/v0.1.3', '1d6d2a023a51862a44fc631af78f625868910b8b1e3b6f20cf02e6558d66d039'),
    ('rma/illustrations/arrival-threshold/v0.1.0', '27266d84ec9ac684494ef8ffb94f86af178266a621412bfbd3135a3f2a38c237'),
    ('rma/plates/contemporary-riverbank/v0.1.0', '802a3e9a0d5aee753e9607cd0bb529ca4297eb42ea69ab9f164a33e6724b02d0'),
    ('rma/diagrams/notice-widening/v0.1.0', 'd0779a831fa4e05de7b4c326dc56bcebd1f7e7a54731a1c5bc2d063633db3a0a'),
    ('rma/diagrams/compare-views/v0.1.0', 'b1f36ab00bfd0798a3ab833c3b55de376ea510fa3ad315db3a4aed59d6be37df'),
    ('rma/diagrams/discern-sort/v0.1.1', '404babef8cb51b786a7600bc1d62513034068d3668c0b970600ee05abeacab77'),
    ('rma/diagrams/return-timeline/v0.1.0', 'f89ac046c55127db83ba3487305c669702565059c9c96c5def5e1576c1c6e1d6'),
    ('rma/diagrams/privacy-boundary/v0.1.1', '286eaa264fcf53401cf2952e22a00a646f3f39055d49f3c132c9a1ea6c605f38'),
]

sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
lock = []
for rel, want in PINS:
    src = LIB / rel
    man = src / 'MANIFEST.sha256'
    got = sha(man)
    if want and got != want:
        sys.exit(f'{rel}: manifest sha {got} != pinned {want}')
    for line in man.read_text().splitlines():
        h, name = line.split(None, 1)
        name = name.lstrip('*')
        f = src / name
        if sha(f) != h:
            sys.exit(f'{rel}/{name}: hash mismatch')
        dst = OUT / rel / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(f, dst)
    shutil.copyfile(man, OUT / rel / 'MANIFEST.sha256')
    lock.append({'path': rel, 'manifest_sha256': got, 'pinned': bool(want)})

sprites = sorted(OUT.glob('rma/icons/*/*/sprite.svg'))
if sprites:
    (OUT / 'sprite.js').write_text('// Generated by scripts/sync-assets.py from ' + str(sprites[-1].relative_to(OUT)) +
        '\nconst RMA_SPRITE = ' + json.dumps(sprites[-1].read_text()) + ';\n')
# Plates: <door-id>.svg with Art's alt text (the alt carries the core content).
plates = {}
for alt in sorted(OUT.glob('rma/plates/*/*/*.alt.txt')):
    svg = alt.with_name(alt.name.replace('.alt.txt', '.svg'))
    if svg.exists():
        plates[svg.stem] = {'src': 'assets/' + str(svg.relative_to(OUT)), 'alt': alt.read_text().strip()}
# Single items: <item>/<version>/<item>.svg, with alt.txt where Art supplies one.
art = {}
for svg in sorted(OUT.glob('rma/*/*/*/*.svg')):
    if svg.stem == svg.parent.parent.name:
        alt = svg.parent / 'alt.txt'
        art[svg.stem] = {'src': 'assets/' + str(svg.relative_to(OUT)), 'alt': alt.read_text().strip() if alt.exists() else ''}
if plates or art:
    (OUT / 'plates.js').write_text('// Generated by scripts/sync-assets.py\nconst RMA_PLATES = ' + json.dumps(plates, indent=1, ensure_ascii=False) + ';\n'
        + 'const RMA_ART = ' + json.dumps(art, indent=1, ensure_ascii=False) + ';\n')
(OUT / 'ASSETS.lock.json').write_text(json.dumps(lock, indent=2) + '\n')
print(json.dumps(lock, indent=2))
